 VALUES(d,item,'40000000-0000-0000-0000-000000000001','entree',1,2,'2020-01-10');
 PERFORM test_reject(format('select reset_stock_history(%L,%L,%L,''QA501'',true)',d,req,preview->>'fingerprint'),'stock a changé');
