 PERFORM test_assert((SELECT count(*)=old_costs FROM cost_entries WHERE source_stock_movement_id IS NOT NULL AND domain_id=d),'late failure restores deleted costs');
 PERFORM test_assert((SELECT count(*)=0 FROM stock_history_resets),'late failure restores reset receipt');
