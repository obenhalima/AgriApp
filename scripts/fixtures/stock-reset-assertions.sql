 SELECT count(*) INTO old_count FROM stock_movements WHERE domain_id=d;
 SELECT count(*) INTO old_costs FROM cost_entries WHERE source_stock_movement_id IS NOT NULL AND domain_id=d;
 preview:=reset_stock_history(d,req);
 PERFORM test_assert(preview->>'status'='preview' AND (preview->>'movements')::int=old_count AND (preview->>'costs')::int=old_costs,'preview includes exact affected records');
 PERFORM test_assert((SELECT count(*)=old_count FROM stock_movements WHERE domain_id=d),'preview does not delete');
 PERFORM test_reject(format('select reset_stock_history(%L,%L,%L,''WRONG'',true)',d,req,preview->>'fingerprint'),'Recopiez');
 PERFORM set_config('app.stock_history_reset',req::text,true);
 PERFORM test_reject('delete from stock_movements where domain_id=''20000000-0000-0000-0000-000000000001''','Mouvement enregistré');
 PERFORM test_reject('delete from cost_entries where source_stock_movement_id is not null','Coût généré');
